import { initializeApp, applicationDefault, getApps } from "firebase-admin/app";
import { getFirestore } from "firebase-admin/firestore";
if (!getApps().length) initializeApp({ credential: applicationDefault(), projectId: "devcomm-os" });
const db = getFirestore();
const all = await db.collection("companies").where("needsResearch","==",true).get();
const byBiz = {}, byCampaign = {};
all.forEach(d => { const x=d.data();
  byBiz[x.businessId||"(none)"] = (byBiz[x.businessId||"(none)"]||0)+1;
  byCampaign[x.discoveryCampaignId||"(none)"] = (byCampaign[x.discoveryCampaignId||"(none)"]||0)+1;
});
console.log("=== backlog needsResearch=true:", all.size, "===");
console.log("by business:", JSON.stringify(byBiz,null,1));
console.log("by campaign:", JSON.stringify(byCampaign,null,1));
const g = await db.doc("settings/global").get();
console.log("dailyAiResearchLimit:", g.data()?.dailyAiResearchLimit, "| enableTaskQueues:", g.data()?.enableTaskQueues);
process.exit(0);
